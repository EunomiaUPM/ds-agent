#!/usr/bin/env python3
"""Build the OpenAPI artefacts in static/specs/openapi from the per-agent YAML sources.

Writes a JSON twin next to every source and merges them into merged_openapi.{yaml,json}, the
document the agents serve at /api/v1/docs. Fails on clashing paths, operation ids or components.
Usage: scripts/build-openapi.py [--check]
"""
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent / "static" / "specs" / "openapi"
SOURCES = [
    "well-known/well_known.yaml",
    "oauth/oauth.yaml",
    "keystore/keystore.yaml",
    "events/events.yaml",
    "auth/auth_agent.yaml",
    "catalog/catalog_agent.yaml",
    "catalog/catalog_dsp.yaml",
    "connector/connector.yaml",
    "contracts/negotiation_agent.yaml",
    "contracts/negotiation_dsp.yaml",
    "transfer/transfer_agent.yaml",
    "transfer/transfer_dsp.yaml",
    "transfer/dataplane.yaml",
]
METHODS = {"get", "put", "post", "delete", "options", "head", "patch", "trace"}
MERGED_INFO = {
    "title": "Eunomia DS Agent API",
    "description": (
        "Every HTTP route of a monolith agent: management APIs, Dataspace Protocol 2025-1 "
        "endpoints, SSI auth, OAuth, events, keystore and dataplane. Generated by "
        "`scripts/build-openapi.py` from the per-agent specs in this folder; do not edit.\n"
    ),
    "version": "1.0.0",
    "license": {"name": "GPL-3.0-or-later", "url": "https://www.gnu.org/licenses/gpl-3.0.html"},
}


class Dumper(yaml.SafeDumper):
    def ignore_aliases(self, data):
        return True


Dumper.add_representer(
    str,
    lambda d, s: d.represent_scalar("tag:yaml.org,2002:str", s, style="|" if "\n" in s else None),
)


def merge(specs):
    merged = {
        "openapi": "3.1.0",
        "info": MERGED_INFO,
        "servers": specs[0][1]["servers"],
        "tags": [],
        "paths": {},
        "components": {},
    }
    tag_names, op_ids, errors = set(), {}, []
    for name, spec in specs:
        root_security = spec.get("security")
        for tag in spec.get("tags", []):
            if tag["name"] not in tag_names:
                tag_names.add(tag["name"])
                merged["tags"].append(tag)
        for path, item in spec.get("paths", {}).items():
            target = merged["paths"].setdefault(path, {})
            for key, op in item.items():
                if key in target and key != "parameters":
                    errors.append(f"{name}: {key.upper()} {path} already defined")
                    continue
                if key in METHODS:
                    op = dict(op)
                    if "security" not in op and root_security is not None:
                        op["security"] = root_security
                    oid = op.get("operationId")
                    if oid in op_ids:
                        errors.append(f"{name}: operationId {oid} also in {op_ids[oid]}")
                    op_ids[oid] = name
                target[key] = op
        for section, items in spec.get("components", {}).items():
            target = merged["components"].setdefault(section, {})
            for comp, value in items.items():
                if comp in target and target[comp] != value:
                    errors.append(f"{name}: components/{section}/{comp} differs from another spec")
                target.setdefault(comp, value)
    if errors:
        sys.exit("merge failed:\n  " + "\n  ".join(errors))
    merged["components"] = {
        s: dict(sorted(v.items())) for s, v in sorted(merged["components"].items())
    }
    return merged


def render(outputs):
    for path, data in outputs.items():
        if path.suffix == ".json":
            yield path, json.dumps(data, indent=2, ensure_ascii=False) + "\n"
        else:
            yield path, yaml.dump(data, Dumper=Dumper, sort_keys=False, allow_unicode=True, width=100)


def main():
    check = "--check" in sys.argv[1:]
    specs = [(name, yaml.safe_load((ROOT / name).read_text())) for name in SOURCES]
    outputs = {(ROOT / name).with_suffix(".json"): spec for name, spec in specs}
    merged = merge(specs)
    outputs[ROOT / "merged_openapi.yaml"] = merged
    outputs[ROOT / "merged_openapi.json"] = merged
    stale = []
    for path, text in render(outputs):
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(path.relative_to(ROOT))
        else:
            path.write_text(text)
    if stale:
        sys.exit("out of date, run scripts/build-openapi.py: " + ", ".join(map(str, stale)))
    print(f"{len(merged['paths'])} paths from {len(specs)} specs")


if __name__ == "__main__":
    main()
